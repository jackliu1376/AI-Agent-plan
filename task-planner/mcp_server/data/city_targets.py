def validate() -> list[str]:
    """返回无法被 ``lookup_city()`` 识别的城市名。空列表表示全部通过。"""
    from mcp_server.data.cities import lookup_city

    bad = []
    for name in CHINA_CITIES + OVERSEAS_CITIES:
        city = lookup_city(name)
        if city is None:
            bad.append(name)
    return bad


def duplicates() -> list[str]:
    """返回重复的城市名（同一城市出现两次会让抓取白跑一遍）。"""
    seen: set[str] = set()
    dup: list[str] = []
    for name in CHINA_CITIES + OVERSEAS_CITIES:
        if name in seen:
            dup.append(name)
        seen.add(name)
    return dup


