    bad = validate()
    dup = duplicates()
    print(f"中国 {len(CHINA_CITIES)} 城 | 海外 {len(OVERSEAS_CITIES)} 城")
    print(f"未识别: {bad if bad else '无'}")
    print(f"重复: {dup if dup else '无'}")
