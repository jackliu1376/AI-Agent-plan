# 抓取数据进入库里的最低条数。低于此值的城市整批丢弃（见 _load_generated_rows）。
GENERATED_MIN_PER_CITY = 6


def _load_generated_rows() -> list[tuple]:
    """加载抓取生成的数据。

    独立文件（``seed_generated.py``）而不是塞进本文件：那批数据是机器生成的、
    有几千行，混在这里会把人工核对的那批淹掉。文件不存在时返回空 ——
    clone 下来没跑过抓取脚本也能正常建库（只有手写的那批）。

    用 ``build_rows(_row)`` 传工厂函数而不是让子模块 import ``_row``：
    子模块 import 本模块会构成循环导入（本模块在 ``SEED_ROWS`` 之后才 import 它）。

    **同名去重**：抓取和手写覆盖同一批城市，会出现「故宫博物院」两条
    （一条 manual、一条 amap）。手写那条字段更可信（票价是核对的、不是估算），
    所以保留手写、丢掉抓取的同名条目。不去重的话查询会返回重复景点，
    计划里会出现两个一模一样的点。
    """
    try:
        from mcp_server.data.seed_generated import build_rows
    except ImportError:
        return []

    rows = build_rows(_row)
    seen = {(r[0], r[2]) for r in SEED_ROWS}  # (city, name)
    rows = [r for r in rows if (r[0], r[2]) not in seen]

    # 抓取质量太差的城市整体丢弃，让位给兜底数据。
    #
    # 「按名搜索」（region 失效时的兜底）对小城市会返回**名字里含该地名的任意
    # POI** —— 实测「海东」返回驾校和考场、「花莲」返回驾驶训练班。这些条目
    # 评分还不低（4.1–4.7），光靠评分门槛拦不住。
    #
    # 判据是条数：真能抓到的城市都在 10 条以上，被垃圾淹没的城市过滤完只剩几条。
    # 与其混进去拉低整个库的可信度，不如不要 —— 那几个城市有 FALLBACK_ROWS 兜底。
    from collections import Counter

    counts = Counter(r[0] for r in rows)
    return [r for r in rows if counts[r[0]] >= GENERATED_MIN_PER_CITY]


SEED_ROWS.extend(_load_generated_rows())


def resolve_db_path() -> Path:
    """数据库路径：优先环境变量，其次默认路径。"""
    custom = env("ATTRACTIONS_DB")
    return Path(custom) if custom else DEFAULT_DB


def _existing_columns(path: Path) -> set[str]:
    try:
        with sqlite3.connect(path) as conn:
            rows = conn.execute("PRAGMA table_info(attractions)").fetchall()
        return {row[1] for row in rows}
    except sqlite3.Error:
        return set()


def _needs_reseed(path: Path) -> bool:
    """结构（列）或种子行数发生变化时需要重建。

    只比行数不够：新增列时旧库不会自动 ALTER，插入会直接失败。
    """
    if not path.exists():
        return True
    if not set(COLUMNS) <= _existing_columns(path):
        return True
    try:
        with sqlite3.connect(path) as conn:
            (count,) = conn.execute("SELECT COUNT(*) FROM attractions").fetchone()
    except sqlite3.Error:
        return True

    # **库里的数据比代码里的多时不要重建。**
    #
    # 这个分支是为「进程还没重启」准备的：改了 seed 数据后，跑着的旧进程内存里
    # 还是旧的 SEED_ROWS，而磁盘上的库已经被新代码重建过（行数更多）。
    # 按原来的 `count != len(SEED_ROWS)` 判断，旧进程会把库**重建成旧数据** ——
    # 于是用户看到的是「明明补了数据却查不到」，而且数据被反复覆盖。
    #
    # 直接读磁盘上那份更全的库即可；代码比数据新（正常升级）时仍会重建。
    if count > len(SEED_ROWS):
        return False
    return count != len(SEED_ROWS)


@contextmanager
def connect(db_path: Path | None = None) -> Iterator[sqlite3.Connection]:
    """打开数据库连接（**上下文管理器，退出时关闭**）。

    - 默认库：文件缺失、结构变化或与种子数据行数不一致时自动重建（保证 clone 即可运行）。
    - 自定义库（通过 ``ATTRACTIONS_DB`` 指定）：只补种缺失文件，不覆盖用户数据。

    为什么返回上下文管理器而不是裸 ``Connection``：
    ``with sqlite3.connect(...) as conn`` **只提交事务，不关闭连接** ——
    这是 sqlite3 的常见误解。连接会一直挂到 CPython 引用计数回收为止；
    一旦被异常栈或 traceback 持有，Windows 上重播库时的 ``DROP TABLE``
    就会报 ``database is locked``。这里在 ``finally`` 里显式关闭，
    调用方写 ``with connect() as conn:`` 即可，不用自己记得关。
    """
    path = db_path or resolve_db_path()
    path.parent.mkdir(parents=True, exist_ok=True)

    custom = bool(env("ATTRACTIONS_DB")) and db_path is None
    if not path.exists() or (not custom and _needs_reseed(path)):
        seed(path)

    conn = sqlite3.connect(path)
    conn.row_factory = sqlite3.Row
    try:
        yield conn
    finally:
        conn.close()


def seed(path: Path | None = None) -> int:
    """建表并写入种子数据。返回写入行数。"""
    target = path or resolve_db_path()
    target.parent.mkdir(parents=True, exist_ok=True)
    placeholders = ", ".join("?" for _ in COLUMNS)
    # closing() 而不是 `with sqlite3.connect(...)`：后者只提交事务、不关连接
    with closing(sqlite3.connect(target)) as conn:
        conn.execute("DROP TABLE IF EXISTS attractions")
        conn.executescript(SCHEMA)
        conn.executemany(
            f"INSERT INTO attractions ({', '.join(COLUMNS)}) VALUES ({placeholders})",
            SEED_ROWS,
        )
        conn.commit()
    return len(SEED_ROWS)


def covered_cities() -> list[str]:
    """返回库中已有数据的城市。"""
    with connect() as conn:
        rows = conn.execute("SELECT DISTINCT city FROM attractions ORDER BY city").fetchall()
    return [r["city"] for r in rows]


