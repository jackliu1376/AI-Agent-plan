def resolve_db_path() -> Path:
    """数据库路径：优先环境变量，其次默认路径。"""
    custom = env("ATTRACTIONS_DB")
    return Path(custom) if custom else DEFAULT_DB


def _existing_columns(path: Path) -> set[str]:
    try:
        with sqlite3.connect(path) as conn:
            rows = conn.execute("PRAGMA table_info(attractions)").fetchall()
        return {row[1] for row in rows}
    except sqlite3.Error:
        return set()


def _needs_reseed(path: Path) -> bool:
    """结构（列）或种子行数发生变化时需要重建。

    只比行数不够：新增列时旧库不会自动 ALTER，插入会直接失败。
    """
    if not path.exists():
        return True
    if not set(COLUMNS) <= _existing_columns(path):
        return True
    try:
        with sqlite3.connect(path) as conn:
            (count,) = conn.execute("SELECT COUNT(*) FROM attractions").fetchone()
        return count != len(SEED_ROWS)
    except sqlite3.Error:
        return True


def connect(db_path: Path | None = None) -> sqlite3.Connection:
    """打开数据库连接。

    - 默认库：文件缺失、结构变化或与种子数据行数不一致时自动重建（保证 clone 即可运行）。
    - 自定义库（通过 ``ATTRACTIONS_DB`` 指定）：只补种缺失文件，不覆盖用户数据。
    """
    path = db_path or resolve_db_path()
    path.parent.mkdir(parents=True, exist_ok=True)

    custom = bool(env("ATTRACTIONS_DB")) and db_path is None
    if not path.exists() or (not custom and _needs_reseed(path)):
        seed(path)

    conn = sqlite3.connect(path)
    conn.row_factory = sqlite3.Row
    return conn


def seed(path: Path | None = None) -> int:
    """建表并写入种子数据。返回写入行数。"""
    target = path or resolve_db_path()
    target.parent.mkdir(parents=True, exist_ok=True)
    placeholders = ", ".join("?" for _ in COLUMNS)
    with sqlite3.connect(target) as conn:
        conn.execute("DROP TABLE IF EXISTS attractions")
        conn.executescript(SCHEMA)
        conn.executemany(
            f"INSERT INTO attractions ({', '.join(COLUMNS)}) VALUES ({placeholders})",
            SEED_ROWS,
        )
        conn.commit()
    return len(SEED_ROWS)


def covered_cities() -> list[str]:
    """返回库中已有数据的城市。"""
    with connect() as conn:
        rows = conn.execute("SELECT DISTINCT city FROM attractions ORDER BY city").fetchall()
    return [r["city"] for r in rows]


